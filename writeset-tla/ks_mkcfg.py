#!/usr/bin/env python3
# Generate KS_<name>.cfg (WritesetSysopKeyed) from defaults overridden by key=value args.
# Usage: ks_mkcfg.py name [k=v ...] [INV=a,b] [SYM=0|1|2] [T=n] [K=n] [S=n]
import sys, shlex
name = sys.argv[1]
d = dict(Txns="{t1, t2}", Keys="{k1, k2}", Serials="{s1}", HashMode='"ident"', CollidePair="{}", KeyLimit="2",
         MaxOps="2", AllowRef="TRUE", AllowOverflow="TRUE", AllowStmt="FALSE", AllowSavepoint="FALSE",
         AllowAbort="TRUE", AllowOOM="FALSE", AllowMasterRestart="FALSE", AllowSerial="TRUE",
         FineGrainPublish="FALSE", Interleave="FALSE", MasterOnly="FALSE", NumWorkers="2", QCap="2",
         RingCap="50", MaxCrash="1", AllowMarkerDdl="FALSE", FixFragStart="TRUE",
         SysopMode='"keyed"', AllowIncr="TRUE", AllowAttach="TRUE", AllowPlainSysop="TRUE",
         AttachFix="TRUE", SafetyCheck="FALSE", Mut='"none"')
d["None"] = "None"
inv = "DepCover DepBelowSelf BarrierWaitsAll NoDuplicate OnlyUnits ConflictOrder PrefixStored RequiredStored QuietAllApplied FinalState"
sym = None
for a in sys.argv[2:]:
    k, v = a.split("=", 1)
    if k == "INV": inv = v.replace(",", " ")
    elif k == "SYM": sym = int(v)
    elif k == "T": d["Txns"] = "{" + ", ".join(f"t{i}" for i in range(1, int(v) + 1)) + "}"
    elif k == "K": d["Keys"] = "{" + ", ".join(f"k{i}" for i in range(1, int(v) + 1)) + "}"
    elif k == "S": d["Serials"] = "{" + ", ".join(f"s{i}" for i in range(1, int(v) + 1)) + "}"
    else: d[k] = v
if sym is None: sym = 2 if d["CollidePair"] == "{}" else 1
with open(f"KS_{name}.cfg", "w") as f:
    f.write(f"\\* generated by ks_mkcfg.py: {' '.join(shlex.quote(a) for a in sys.argv[2:])}\nCONSTANTS\n")
    for k, v in d.items(): f.write(f"  {k} = {v}\n")
    f.write("SPECIFICATION Spec\n")
    if sym == 1: f.write("SYMMETRY TxnSym\n")
    if sym == 2: f.write("SYMMETRY TxnKeySym\n")
    f.write(f"INVARIANTS {inv}\n")

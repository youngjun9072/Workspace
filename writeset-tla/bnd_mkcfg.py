#!/usr/bin/env python3
# Generate BND_<name>.cfg for WritesetBoundary.tla from defaults overridden by key=value args.
# Usage: bnd_mkcfg.py name [k=v ...] [INV=a,b] [SYM=0|1] [T=n] [K=n]
import sys, shlex
name = sys.argv[1]
d = dict(Txns="{t1, t2}", Keys="{k1}", MaxD="2", MaxS="1", MaxCD="1", MaxItems="1", AllowAbort="TRUE",
         Interleave="FALSE", NumWorkers="2", QCap="2", RingCap="50", MaxCrash="1", FixFragStart='"both"',
         FailModel="FALSE", AllowIgnoreFail="FALSE", AllowFlushRestart="FALSE", AllowCommitFail="FALSE",
         AllowServerAbortRetry="FALSE", MaxErr="0", Failover="FALSE", Mut='"none"')
d["None"] = "None"
inv = "NoDuplicate OnlyUnits UnitAtomic MarkerWithData ConflictOrder PrefixStored RequiredStored QuietAllApplied PromoteComplete"
sym = 1
for a in sys.argv[2:]:
    k, v = a.split("=", 1)
    if k == "INV": inv = v.replace(",", " ")
    elif k == "SYM": sym = int(v)
    elif k == "T": d["Txns"] = "{" + ", ".join(f"t{i}" for i in range(1, int(v) + 1)) + "}"
    elif k == "K": d["Keys"] = "{" + ", ".join(f"k{i}" for i in range(1, int(v) + 1)) + "}"
    else: d[k] = v
with open(f"BND_{name}.cfg", "w") as f:
    f.write(f"\\* generated by bnd_mkcfg.py: {' '.join(shlex.quote(a) for a in sys.argv[2:])}\nCONSTANTS\n")
    for k, v in d.items(): f.write(f"  {k} = {v}\n")
    f.write("SPECIFICATION Spec\n")
    if sym == 1: f.write("SYMMETRY TxnSym\n")
    f.write(f"INVARIANTS {inv}\n")

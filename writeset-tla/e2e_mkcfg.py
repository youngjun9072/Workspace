#!/usr/bin/env python3
# Generate E2E_<name>.cfg from defaults overridden by key=value args.
# Usage: e2e_mkcfg.py name [k=v ...] [INV=a,b] [SYM=0|1|2] [T=n] [K=n]
#   T=n / K=n: Txns {t1..tn} / Keys {k1..kn}; SYM 0 none, 1 transactions, 2 transactions and keys (default:
#   2, or 1 when CollidePair is not empty; simulation ignores symmetry, use SYM=0 there)
import sys, shlex
name = sys.argv[1]
d = dict(Txns="{t1, t2}", Keys="{k1, k2}", Serials="{s1}", HashMode='"ident"', CollidePair="{}", KeyLimit="2",
         MaxOps="2", AllowRef="TRUE", AllowOverflow="TRUE", AllowStmt="TRUE", AllowSavepoint="TRUE",
         AllowAbort="TRUE", AllowOOM="TRUE", AllowMasterRestart="TRUE", AllowSerial="TRUE",
         FineGrainPublish="TRUE", Interleave="FALSE", MasterOnly="FALSE", NumWorkers="2", QCap="2",
         RingCap="50", MaxCrash="1", AllowMarkerDdl="FALSE", FixFragStart="TRUE", Mut='"none"')
d["None"] = "None"
inv = "DepCover DepBelowSelf BarrierWaitsAll NoDuplicate OnlyUnits ConflictOrder PrefixStored RequiredStored QuietAllApplied FinalState"
sym = None
for a in sys.argv[2:]:
    k, v = a.split("=", 1)
    if k == "INV": inv = v.replace(",", " ")
    elif k == "SYM": sym = int(v)
    elif k == "T": d["Txns"] = "{" + ", ".join(f"t{i}" for i in range(1, int(v) + 1)) + "}"
    elif k == "K": d["Keys"] = "{" + ", ".join(f"k{i}" for i in range(1, int(v) + 1)) + "}"
    else: d[k] = v
if sym is None: sym = 2 if d["CollidePair"] == "{}" else 1
with open(f"E2E_{name}.cfg", "w") as f:
    f.write(f"\\* generated by e2e_mkcfg.py: {' '.join(shlex.quote(a) for a in sys.argv[2:])}\nCONSTANTS\n")
    for k, v in d.items(): f.write(f"  {k} = {v}\n")
    f.write("SPECIFICATION Spec\n")
    if sym == 1: f.write("SYMMETRY TxnSym\n")
    if sym == 2: f.write("SYMMETRY TxnKeySym\n")
    f.write(f"INVARIANTS {inv}\n")
